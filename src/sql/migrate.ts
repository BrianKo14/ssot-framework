// The schema comparator

import type { TableInfo } from '../schema/model.js';
import type { Catalog } from './catalog.js';
import { script, type Target, targets } from './ddl.js';

/** A list of targets that are missing from the database.
 * New objects are created. Existing ones are descended into. */
const missingIn = (target: Target, held: Catalog): Target[] =>
	held.has(target.key) ? (target.parts ?? []).flatMap(part => missingIn(part, held)) : [target];

/** A list of all the targets that are missing from the database. */
export const missing = (tables: TableInfo[], held: Catalog): Target[] =>
	targets(tables).flatMap(target => missingIn(target, held));

/** The script that adds them. */
export const updateSql = (additions: Target[]): string =>
	script(additions.map(target => target.sql),
		'Generated by comparing the system definition against the database.\n'
		+ 'Additions only (SCOPE 5a): nothing here removes or changes what is already there.');
